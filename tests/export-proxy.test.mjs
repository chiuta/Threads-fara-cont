// Teste v2.1.0: export Markdown al listei și proxy-ul opțional (proxy/cloudflare-worker.js, cu fetch simulat).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
const require = createRequire(process.env.PW_ROOT || import.meta.url);
const {chromium} = require('playwright');
const HERE = path.dirname(fileURLToPath(import.meta.url));
const FILE = 'file://' + path.join(HERE, '..', 'index.html');
let ok = 0, bad = 0;
const check = (n, c, x) => { if (c) { ok++; console.log('  ok   ' + n); } else { bad++; console.log('  FAIL ' + n + (x !== undefined ? '  → ' + JSON.stringify(x) : '')); } };
const TMP = fs.mkdtempSync(path.join(process.env.FFF_TMP || os.tmpdir(), 'thr21-'));

console.log('— proxy (fetch simulat)');
const W = await import(pathToFileURL(path.join(HERE, '..', 'proxy', 'cloudflare-worker.js')).href);
const calls = [];
const fakeFetch = async (u, init) => { calls.push({u, init}); return new Response('{"html":"<blockquote>x</blockquote>"}', {status: 200}); };
const direct = 'https://graph.threads.net/v1.0/oembed?url=' + encodeURIComponent('https://www.threads.com/@a/post/B1') + '&maxwidth=550';
const req = (target, o = {}) => new Request('https://px.example/?url=' + encodeURIComponent(target), {method: o.method || 'GET', headers: o.headers || {origin: 'https://chiuta.github.io'}});
let r = await W.handle(req(direct), {}, fakeFetch);
check('cerere validă → 200 + CORS pentru originea permisă', r.status === 200 && r.headers.get('access-control-allow-origin') === 'https://chiuta.github.io', [r.status]);
check('retransmite doar către graph.threads.net, fără cookie/referer', calls.length === 1 && calls[0].u.startsWith('https://graph.threads.net/v1.0/oembed?') && !calls[0].init.headers.cookie && !calls[0].init.headers.referer, calls);
r = await W.handle(req('https://evil.example/x'), {}, fakeFetch);
check('alt host → 400 (nu e proxy deschis)', r.status === 400);
r = await W.handle(req('https://graph.threads.net/v1.0/me?access_token=x'), {}, fakeFetch);
check('alt endpoint Meta → 400', r.status === 400);
r = await W.handle(req('https://graph.threads.net/v1.0/oembed?url=' + encodeURIComponent('https://evil.example/p')), {}, fakeFetch);
check('postare non-Threads → 400', r.status === 400);
r = await W.handle(req(direct, {headers: {origin: 'https://evil.example'}}), {}, fakeFetch);
check('origine străină → 403', r.status === 403);
r = await W.handle(req(direct, {headers: {origin: 'https://me.example'}}), {ALLOWED_ORIGIN: 'https://me.example'}, fakeFetch);
check('ALLOWED_ORIGIN configurabil', r.status === 200 && r.headers.get('access-control-allow-origin') === 'https://me.example');
r = await W.handle(req(direct, {method: 'POST'}), {}, fakeFetch);
check('POST → 405', r.status === 405);
r = await W.handle(new Request('https://px.example/', {method: 'OPTIONS'}), {}, fakeFetch);
check('OPTIONS → 204', r.status === 204);
r = await W.handle(new Request('https://px.example/'), {}, fakeFetch);
check('fără url → 400', r.status === 400);
r = await W.handle(req(direct), {}, async () => { throw new Error('x'); });
check('upstream căzut → 502', r.status === 502);
check('antet no-store', (await W.handle(req(direct), {}, fakeFetch)).headers.get('cache-control') === 'no-store');

console.log('— export Markdown în aplicație');
const b = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox']});
const ctx = await b.newContext({acceptDownloads: true, locale: 'ro-RO'});
await ctx.route(/^https?:/, (r) => {
  const u = new URL(r.request().url());
  if (u.hostname === 'graph.threads.net') return r.fulfill({status: 200, contentType: 'application/json', headers: {'access-control-allow-origin': '*'}, body: JSON.stringify({html: '<blockquote class="text-post-media">salut <a href="https://www.threads.com/@maria/post/ABC123">link</a></blockquote>', author_name: 'maria*_x'})});
  r.abort();
});
const p = await ctx.newPage();
const errs = [];
p.on('pageerror', (e) => errs.push(e.message));
p.on('console', (m) => { if (/Content Security Policy|Refused to/i.test(m.text())) errs.push(m.text()); });
await p.goto(FILE); await p.waitForTimeout(400);
await p.fill('#urlInput', 'https://www.threads.com/@maria/post/ABC123');
await p.click('#addBtn'); await p.waitForTimeout(600);
await p.click('#exportBtn');
const [d] = await Promise.all([p.waitForEvent('download'), p.click('#ioDownloadMd')]);
const fp = path.join(TMP, d.suggestedFilename()); await d.saveAs(fp);
const md = fs.readFileSync(fp, 'utf8');
check('nume threads-lista.md', d.suggestedFilename() === 'threads-lista.md');
check('titlu + link ca element de listă', /^# Threads\n/.test(md) && /- <https:\/\/www\.threads\.com\/@maria\/post\/ABC123>/.test(md), md);
check('caracterele Markdown din nume sunt neutralizate', !/maria\*_x/.test(md) || /maria\\\*\\_x/.test(md), md);
check('etichetă tradusă (ro)', await p.evaluate(() => document.getElementById('ioDownloadMd').textContent === 'Descarcă .md'));
await p.selectOption('#langSelect', 'de');
check('etichetă tradusă (de)', await p.evaluate(() => document.getElementById('ioDownloadMd').textContent === 'Markdown herunterladen'));
check('fără pageerror/CSP', errs.length === 0, errs);
await b.close();
console.log('\n' + ok + ' ok, ' + bad + ' eșuate');
process.exit(bad ? 1 : 0);
